import {test,expect} from '@playwright/test';
test.use({deviceScaleFactor:.3});
const debug=page=>page.evaluate(()=>window.__scalpless.getDebug());
const peel=async(page,id)=>{
  await page.locator('#piece-select').selectOption(id);
  for(let i=0;i<4&&!(await debug(page)).state.pieces[id].detached;i++)await page.locator('#primary-action').click();
  await expect.poll(async()=>(await debug(page)).state.pieces[id].detached).toBe(true);
  await page.locator('#place-action').click();
  await expect.poll(async()=>(await debug(page)).state.held).toBe(null);
};
test('guided lesson walks through the whole dissection',async({page})=>{
  await page.goto('/lab.html');
  await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  const lesson=page.locator('#lesson'),title=lesson.locator('.lesson-title');
  await expect(title).toHaveText('Pick up the scalpel');
  await expect(page.locator('[data-tool="scalpel"]')).toHaveClass(/lesson-target/);
  await page.keyboard.press('s');
  await expect(title).toHaveText('Cut along the seam');
  await page.locator('#primary-action').click();
  await expect(title).toHaveText('Switch to forceps',{timeout:60000});
  await page.keyboard.press('h');
  await expect(title).toHaveText('Lift the cut section away');
  await page.locator('#primary-action').click();
  await page.locator('#place-action').click();
  await expect(title).toHaveText('Peel the outer layer');
  await peel(page,'layer-0');
  await expect(title).toHaveText('Peel the next layer');
  await peel(page,'layer-1');
  await expect(title).toHaveText('Peel off the epidermis');
  await peel(page,'epidermis');
  await expect(title).toHaveText('Inspect it under the microscope');
  await page.keyboard.press('m');
  await page.keyboard.press('Escape');
  await expect(lesson.locator('.lesson-count')).toHaveText('Lesson complete');
  // Hiding persists across reloads; the toolbar toggle brings it back.
  await lesson.locator('.lesson-close').click();
  await expect(lesson).toBeHidden();
  await page.reload();
  await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  await expect(page.locator('#lesson')).toBeHidden();
  await page.locator('#lesson-toggle').click();
  await expect(page.locator('#lesson .lesson-title')).toHaveText('Pick up the scalpel');
});
