import {test,expect} from '@playwright/test';
test.use({deviceScaleFactor:.3});
const debug=page=>page.evaluate(()=>window.__scalpless.getDebug());
test('original onion UI supports keyboard incision, mouse pickup, placement, peeling and reset',async({page})=>{
  await page.goto('/');
  await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  await page.keyboard.press('s');
  await page.locator('#primary-action').click();
  await expect.poll(async()=>(await debug(page)).state.cutOpen,{timeout:60000}).toBe(true);
  await page.keyboard.press('h');
  const grasp=(await debug(page)).graspPoints.section;
  const size=page.viewportSize();
  await page.mouse.move(grasp.x*size.width,grasp.y*size.height);
  await page.mouse.down();
  await expect.poll(async()=>(await debug(page)).state.held).toBe('section');
  await page.mouse.move((grasp.x+.17)*size.width,(grasp.y-.03)*size.height,{steps:5});
  await page.mouse.up();
  await expect.poll(async()=>(await debug(page)).state.available.some(p=>p.id==='layer-0')).toBe(true);
  await page.locator('#piece-select').selectOption('section');
  await page.locator('#primary-action').click();
  await page.locator('#place-action').click();
  await page.waitForTimeout(1500);
  const placed=await debug(page);
  expect(placed.bounds.section.min[1],JSON.stringify(placed.bounds.section)).toBeGreaterThan(-.015);
  await page.locator('#piece-select').selectOption('layer-0');
  for(let i=0;i<4;i++)await page.locator('#primary-action').click();
  await expect.poll(async()=>(await debug(page)).state.pieces['layer-0'].detached).toBe(true);
  await page.locator('#place-action').click();
  await expect.poll(async()=>(await debug(page)).state.held).toBe(null);
  await page.locator('#reset').click();
  const reset=await debug(page);
  expect(reset.state.cut).toBe(0);expect(reset.state.held).toBe(null);expect(reset.physicsBodies).toBe(0);
});
